'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { buildManifest, canonicalSerialize, manifestRoot, validateManifest } = require('../manifest');
const { drawPack, drawPackForOpen, drawBlockHeight } = require('../draw');
const { verifyPack, verifyMint } = require('../verify');
const hash = s => createHash('sha256').update(s).digest('hex');
const designs = Array.from({length:1000}, (_, id) => ({id, ref:`bafy...design${id}`, weight:id<900?100:id<990?10:1}));
const m = buildManifest({name:'Genesis Series', pack_size:10, allow_pack_duplicates:false, designs, slots:{'9':{table:designs.slice(990).map(({id})=>({id,weight:1}))}}});
const vectors = JSON.parse(fs.readFileSync(require.resolve('../v3_vectors.json'),'utf8'));
const first = drawPack(m,'box-alpha',hash('block3'));
assert.deepEqual(first.designs,vectors.first_pack);
// Preserve the historical fixture root; publication now commits slot_odds too.
const legacy = structuredClone(m); delete legacy.slot_odds;
assert.notEqual(manifestRoot(m),manifestRoot(legacy));
const generated = {note:vectors.note,D:1,manifest_root:manifestRoot(legacy),example_box:'box-alpha',first_open_height:2,first_pack:first.designs,reopened_pack:drawPack(m,'box-alpha',hash('block8')).designs};
assert.deepEqual(generated,vectors);
// Git Windows checkout may convert LF to CRLF; no protocol bytes are normalized.
assert.equal(JSON.stringify(generated,null,2),fs.readFileSync(require.resolve('../v3_vectors.json'),'utf8').replace(/\r\n/g,'\n'));
assert.equal(canonicalSerialize({'\u{10000}':'é','\ue000':'😀','10':10,'2':2}),'{"10":10,"2":2,"\\ue000":"\\ud83d\\ude00","\\ud800\\udc00":"\\u00e9"}');
assert.throws(()=>canonicalSerialize({x:NaN}));
assert.throws(()=>canonicalSerialize({x:1.5}));
assert.throws(()=>canonicalSerialize({x:undefined}));
assert.throws(()=>canonicalSerialize({x:Number.MAX_SAFE_INTEGER+1}));
assert.equal(drawBlockHeight(2),3);
assert.equal(drawBlockHeight(2,0),2);
assert.equal(drawPackForOpen(m,'b',null,()=>{throw Error('must not lookup');}),null);
assert.equal(drawPackForOpen(m,'b',2,()=>null),null);
assert.deepEqual(drawPackForOpen(m,'box-alpha',2,h=>hash(`block${h}`)).designs,first.designs);
assert.deepEqual(drawPackForOpen(m,'box-alpha',3,h=>hash(`block${h}`),0).designs,first.designs);
assert(verifyPack(m,'box-alpha',hash('block3'),first.designs));
assert(!verifyPack(m,'box-alpha',hash('block3'),first.designs.toReversed()));
assert(!verifyPack(m,'box-alpha',hash('block3'),first.designs.slice(1)));
assert(!verifyPack(m,'box-alpha',hash('block3'),first.designs.map(String)));
assert(!verifyPack(m,'box-alpha',hash('block3'),Array(10)));
assert(!verifyMint(m,'box-alpha',null,()=>null,first.designs));
assert(!verifyMint(m,'box-alpha',2,()=>null,first.designs));
assert(verifyMint(m,'box-alpha',2,h=>hash(`block${h}`),first.designs));
const small = buildManifest({name:'small',pack_size:3,allow_pack_duplicates:false,per_slot_odds_published:true,designs:[{id:0,ref:'a',weight:100},{id:1,ref:'b',weight:1},{id:2,ref:'c',weight:1}]});
const rejection = drawPack(small,'box','seed');
assert(rejection.retries>0);
assert.equal(new Set(rejection.designs).size,3);
const script = `console.log(JSON.stringify(require('./draw').drawPack(${JSON.stringify(small)},'box','seed')))`;
const run = () => execFileSync(process.execPath,['-e',script],{cwd:require('node:path').join(__dirname,'..'),encoding:'utf8'});
assert.equal(run(),run());
assert.deepEqual(JSON.parse(run()),rejection);
const own = buildManifest({name:'scope',pack_size:2,allow_pack_duplicates:false,designs:[{id:1,ref:'x',weight:1}],slots:{'1':{table:[{id:1,weight:1}]}}});
assert.deepEqual(drawPack(own,'b','s').designs,[1,1]);
const dup = buildManifest({name:'dup',pack_size:3,allow_pack_duplicates:true,designs:[{id:1,ref:'x',weight:1}]});
assert.deepEqual(drawPack(dup,'b','s').designs,[1,1,1]);
for(const mutate of [x=>x.total_weight++,x=>x.designs[0].weight=0,x=>x.designs[0].weight=-1,x=>x.designs[0].weight=0.5,x=>x.designs[1].id=0,x=>x.pack_size=4,x=>x.slots={'3':{table:[{id:0,weight:1}],total_weight:1}},x=>x.slots={'0':{table:[{id:99,weight:1}],total_weight:1}},x=>x.allow_pack_duplicates='false']) {
 const bad=structuredClone(small); mutate(bad); assert.throws(()=>validateManifest(bad));
}
assert.equal(new Set(first.designs.slice(0,9)).size,9);
